-- [Archetype Convention Addition] Migración Flyway del modelo relacional del DAS (figura 1, ER).
-- Las 10 entidades se crean completas; el arquetipo solo mapea en JPA las que usa su flujo.

CREATE TABLE usuario (
    usuario_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(80)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol           VARCHAR(30)  NOT NULL,
    activo        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE formula (
    formula_id            VARCHAR(20)  PRIMARY KEY,
    nombre                VARCHAR(100) NOT NULL,
    descripcion           TEXT,
    activo                BOOLEAN      NOT NULL DEFAULT TRUE,
    estado                VARCHAR(30)  NOT NULL DEFAULT 'NO_PROCESADO',
    ultimo_dictamen       VARCHAR(30),
    fecha_ultima_revision TIMESTAMP,
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE barrido (
    barrido_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado              VARCHAR(30) NOT NULL,
    fecha_inicio        TIMESTAMP   NOT NULL,
    fecha_fin           TIMESTAMP,
    total_formulas      INTEGER,
    total_procesadas    INTEGER,
    total_con_conflicto INTEGER,
    total_sin_conflicto INTEGER,
    total_fallidos      INTEGER,
    mensaje_error       TEXT
);

CREATE TABLE evaluacion_formula (
    evaluacion_id      UUID         PRIMARY KEY,
    formula_id         VARCHAR(20)  NOT NULL REFERENCES formula (formula_id),
    ticket             VARCHAR(100) NOT NULL UNIQUE,
    estado             VARCHAR(30)  NOT NULL,
    dictamen           VARCHAR(30),
    componentes        JSONB,
    fecha_solicitud    TIMESTAMP    NOT NULL,
    fecha_finalizacion TIMESTAMP,
    intentos_callback  INTEGER      NOT NULL DEFAULT 0,
    mensaje_error      TEXT
);

CREATE TABLE patente (
    patente_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_patente  VARCHAR(100) NOT NULL UNIQUE,
    titulo          VARCHAR(255) NOT NULL,
    tipo_producto   VARCHAR(60),
    resumen         TEXT,
    reivindicaciones TEXT,
    fecha_solicitud DATE,
    fecha_concesion DATE,
    fecha_vencimiento DATE,
    jurisdiccion    VARCHAR(50),
    estado_vigencia VARCHAR(30),
    fuente          VARCHAR(100),
    url_fuente      TEXT,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Tabla append-only con retención mínima de 12 meses (DA-10).
CREATE TABLE revision_formula (
    revision_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formula_id     VARCHAR(20)  NOT NULL REFERENCES formula (formula_id),
    barrido_id     BIGINT REFERENCES barrido (barrido_id),
    usuario_id     BIGINT REFERENCES usuario (usuario_id),
    evaluacion_id  UUID   REFERENCES evaluacion_formula (evaluacion_id),
    origen         VARCHAR(30)  NOT NULL,
    fecha_revision TIMESTAMP    NOT NULL,
    resultado      VARCHAR(30)  NOT NULL,
    parametros     JSONB,
    trace_id       VARCHAR(100),
    mensaje_error  TEXT
);

-- El PB exige conflictoId de 6 dígitos: la identidad inicia en 100000.
CREATE TABLE conflicto (
    conflicto_id       BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
    revision_id        BIGINT       NOT NULL REFERENCES revision_formula (revision_id),
    formula_id         VARCHAR(20)  NOT NULL REFERENCES formula (formula_id),
    patente_id         BIGINT       NOT NULL REFERENCES patente (patente_id),
    usuario_descarte_id BIGINT      REFERENCES usuario (usuario_id),
    estado             VARCHAR(20)  NOT NULL,
    fecha_deteccion    TIMESTAMP    NOT NULL,
    motivo_descarte    TEXT,
    fecha_descarte     TIMESTAMP,
    created_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_conflicto_formula_patente UNIQUE (formula_id, patente_id)
);

CREATE INDEX ix_conflicto_formula_estado ON conflicto (formula_id, estado);

-- Una sola fila por conflicto: garantiza idempotencia del envío (P13).
CREATE TABLE notificacion (
    notificacion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conflicto_id    BIGINT      NOT NULL UNIQUE REFERENCES conflicto (conflicto_id),
    tipo            VARCHAR(40) NOT NULL,
    estado          VARCHAR(30) NOT NULL,
    fecha_creacion  TIMESTAMP   NOT NULL,
    fecha_envio     TIMESTAMP,
    intentos        INTEGER     NOT NULL DEFAULT 0,
    mensaje_error   TEXT
);

-- Historial append-only: cada cambio inserta una fila nueva; solo una fila activa a la vez (DA-10).
CREATE TABLE configuracion (
    configuracion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT REFERENCES usuario (usuario_id),
    frecuencia_valor INTEGER     NOT NULL,
    frecuencia_unidad VARCHAR(10) NOT NULL,
    frecuencia_horas INTEGER     NOT NULL,
    rango_cantidad   INTEGER,
    rango_unidad     VARCHAR(10),
    clasificaciones  JSONB       NOT NULL,
    activa           BOOLEAN     NOT NULL,
    vigente_desde    TIMESTAMP   NOT NULL,
    trace_id         VARCHAR(100)
);

CREATE UNIQUE INDEX uq_configuracion_activa ON configuracion (activa) WHERE activa;

CREATE TABLE clasificacion_patente (
    clasificacion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(15) NOT NULL UNIQUE,
    descripcion      TEXT,
    tipo             VARCHAR(3)  NOT NULL
);
